export type PhName = keyof typeof ICONS;

/** An icon of the set, with the classes the stylesheet gives icons (`ph ph-hand`). */
export function Ph({
  name,
  fill,
  className,
  style,
}: {
  name: PhName;
  fill?: boolean;
  className?: string;
  style?: React.CSSProperties;
}) {
  const Glyph = ICONS[name];
  return (
    <Glyph
      className={cx(fill ? 'ph-fill' : 'ph', `ph-${name}`, className)}
      weight={fill ? 'fill' : 'regular'}
      style={style}
      aria-hidden="true"
    />
  );
}
